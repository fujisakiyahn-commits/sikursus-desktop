    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
 try {
        String kodeKursus = txtkodekursus.getText().trim();
        String namaKursus = cmbKursus.getSelectedItem().toString();
        String level = cmblevel.getSelectedItem().toString();

        double biaya = Double.parseDouble(txtBiaya.getText().trim());
        double diskon = Double.parseDouble(txtdiskon.getText().trim());

        Kursus kursus = new Kursus(
            kodeKursus,
            namaKursus,
            level,
            biaya
        );

        double totalBiaya = kursus.hitungBiayaSetelahDiskon(diskon);

        String hasil = "HASIL PENDAFTARAN KURSUS\n"
                + "============================\n"
                + "Kode Kursus  : " + kodeKursus + "\n"
                + "Nama Kursus  : " + namaKursus + "\n"
                + "Level        : " + level + "\n"
                + "Biaya Kursus : Rp " + String.format("%,.0f", biaya) + "\n"
                + "Diskon       : " + diskon + "%\n"
                + "Total Biaya  : Rp " + String.format("%,.0f", totalBiaya);

        txtHasil.setText(hasil);

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Biaya dan Diskon harus diisi dengan angka!",
            "Input Tidak Valid",
            javax.swing.JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnProsesActionPerformed

